"""Run showcase SQL against the seeded database and write docs/SAMPLE_QUERIES.md (CO3 evidence).

    python seed.py && python docs/sample_queries.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from app.db import connect  # noqa: E402

DB = os.environ.get("HACKTRACK_DB", os.path.join(ROOT, "instance", "hacktrack.db"))

QUERIES = [
    ("SELECT with JOIN: a player's next 5 deadlines with their type",
     """SELECT o.title, o.type, o.deadline, o.status
FROM opportunities o JOIN users u ON u.id = o.user_id
WHERE u.username = 'demo' AND o.status IN ('interested','preparing','registered')
  AND o.deadline >= datetime('now','localtime')
ORDER BY o.deadline LIMIT 5;"""),
    ("GROUP BY with aggregate: success rate by quest type",
     """SELECT type, COUNT(*) AS quests,
       SUM(status IN ('won','shortlisted')) AS finals_or_wins,
       ROUND(100.0 * SUM(status IN ('won','shortlisted')) / COUNT(*), 1) AS success_pct
FROM opportunities WHERE user_id = 1
GROUP BY type ORDER BY quests DESC;"""),
    ("Subquery: quests that have no back-plan yet",
     """SELECT title, deadline FROM opportunities
WHERE user_id = 1 AND status IN ('interested','preparing','registered')
  AND id NOT IN (SELECT DISTINCT opportunity_id FROM milestones)
ORDER BY deadline LIMIT 5;"""),
    ("Three-table JOIN: who in the party covers which required skill",
     """SELECT s.name AS skill, os.importance, u.username, us.proficiency
FROM teams t
JOIN opportunity_skills os ON os.opportunity_id = t.opportunity_id
JOIN skills s ON s.id = os.skill_id
JOIN team_members tm ON tm.team_id = t.id AND tm.status = 'active'
JOIN users u ON u.id = tm.user_id
LEFT JOIN user_skills us ON us.user_id = u.id AND us.skill_id = s.id
WHERE t.name = 'Pixel Pirates' AND us.proficiency IS NOT NULL
ORDER BY s.name, us.proficiency DESC;"""),
    ("Recursive CTE: a back-plan phase and all its child milestones",
     """WITH RECURSIVE tree(id, title, depth) AS (
  SELECT id, title, 0 FROM milestones WHERE parent_id IS NULL AND opportunity_id = 1 AND title = 'Build'
  UNION ALL
  SELECT m.id, m.title, tree.depth + 1 FROM milestones m JOIN tree ON m.parent_id = tree.id
)
SELECT depth, title FROM tree;"""),
    ("XP per month (strftime + GROUP BY) for the heatmap / insights",
     """SELECT strftime('%Y-%m', created_at) AS month, COUNT(*) AS actions, SUM(points) AS xp
FROM xp_events WHERE user_id = 1
GROUP BY month ORDER BY month DESC LIMIT 6;"""),
    ("UPDATE (DML): move a quest forward in the pipeline",
     """UPDATE opportunities SET status = 'registered', registered_at = datetime('now','localtime')
WHERE id = 2 AND user_id = 1;"""),
    ("INSERT (DML): award XP",
     """INSERT INTO xp_events (user_id, action, points, ref) VALUES (1, 'journal', 20, 'docs-demo');"""),
    ("DELETE (DML): clear read notifications",
     """DELETE FROM notifications WHERE user_id = 1 AND is_read = 1;"""),
]


def table(rows):
    if not rows:
        return "_(no rows)_"
    cols = rows[0].keys()
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def main():
    conn = connect(DB)
    parts = ["# Sample SQL queries with real output", "",
             "Generated by `python docs/sample_queries.py` against the seeded demo database.",
             "DML statements run inside a transaction that is rolled back, so the demo data is unchanged.", ""]
    for title, sql in QUERIES:
        parts += [f"## {title}", "", "```sql", sql, "```", ""]
        try:
            cur = conn.execute(sql)
            if sql.lstrip().upper().startswith(("UPDATE", "INSERT", "DELETE")):
                parts.append(f"Rows affected: **{cur.rowcount}**")
            else:
                parts.append(table(cur.fetchall()))
        except Exception as exc:  # keep going so one bad query doesn't hide the rest
            parts.append(f"Error: `{exc}`")
        parts.append("")
    conn.rollback()
    conn.close()
    path = os.path.join(ROOT, "docs", "SAMPLE_QUERIES.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
